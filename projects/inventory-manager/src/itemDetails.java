public class itemDetails {

    private double item_cost;           //Cost price of the item
    private double item_sell;           //Selling price of the item
    private int t_quantity_bought;      //Total quantity of the item purchased
    private int t_quantity_sold;        //Total quantity of the item sold

    /**
     * Construct ItemDetail class that initializes item_cost, item_sell, t_quantity_bought, t_quantity_sold variable
     * @param item_cost cost price of the item
     * @param item_sell selling price of the item
     */
    public itemDetails(double item_cost , double item_sell){
        this.item_cost = item_cost;
        this.item_sell  = item_sell;
        this.t_quantity_bought = 0;
        this.t_quantity_sold = 0;
    }

    /**
     * Return cost price of the item
     * @return cost price of the item
     */
    public double get_item_cost(){
        return item_cost;
    }

    /**
     * Return selling price of the item
     * @return selling price of the items
     */
    public double get_item_sell(){
        return item_sell;
    }

    /**
     * Updates the total number of item bought
     * @param number number of item
     * @return total number of item bought
     */
    public int t_quantity_bought(int number){
        t_quantity_bought += number;
        return t_quantity_bought;
    }

    /**
     * Updates the number of item sold
     * @param number number of item
     * @return total number of item sold
     */
    public int t_quantity_sold(int number){
        t_quantity_sold += number;
        return t_quantity_sold;
    }

    /**
     * Returns the remaining quantity of item
     * @return remaining quantity of item
     */
    public int rem_quantity(){
        return t_quantity_bought - t_quantity_sold;
    }

    /**
     * Calculate the profit geneerated by the item
     * @return total profit from the item
     */
    public double profit(){
        double t_amount_bought = t_quantity_bought * item_cost;
        double t_amount_sold = t_quantity_sold * item_sell;

        double profit = t_amount_sold - t_amount_bought;
        return profit;
    }




}
